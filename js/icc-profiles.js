const decode = (b64) => {
  const bin = atob(b64.replace(/\s+/g, ''));
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
};

/** { icc: Uint8Array|null, jfifApp0: boolean } for a camera make. */
export function cameraAppProfile(make) {
  const e = CAMERA_ICC[make];
  if (!e) return { icc: null, jfifApp0: false };
  return { icc: decode(e.icc), jfifApp0: !!e.jfifApp0 };
}
