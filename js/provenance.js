/**
 * Build the XMP packet an export carries, in the measured form.
 *
 * Two sources were measured: a Camera Raw export of a raw file, whose packet
 * leads with xmp:ModifyDate and carries the aux: block the raw supplied, and
 * a Lightroom export of a phone JPEG, which leads with xmp:CreatorTool. The
 * capture time goes to CreateDate and DateCreated; the export time to
 * ModifyDate, MetadataDate and the history entry. History entries are in
 * Adobe's compact attribute form, followed by DerivedFrom, the four tone
 * curves and PointColors, then the padding.
 */
export function buildXmpPacket({ capture, exportAt, offsetCapture, offsetExport, subsec,
                                 lens, editor, source, scene, aux = {} }) {
  const id = uuid();
  const created  = xmpDate(capture, offsetCapture, subsec);
  const modified = xmpDate(exportAt, offsetExport);
  const original = hex(32).toUpperCase();
  const isRaw = !!source.raw;
  const A = [];
  if (isRaw) {
    A.push(['xmp:ModifyDate', modified], ['xmp:CreateDate', created],
           ['xmp:CreatorTool', editor.software], ['xmp:MetadataDate', modified]);
    if (aux.serialNumber) A.push(['aux:SerialNumber', aux.serialNumber]);
    if (lens?.lensInfo)   A.push(['aux:LensInfo', lens.lensInfo]);
    if (lens?.auxLens)    A.push(['aux:Lens', xml(lens.auxLens)]);
    if (aux.lensSerial)   A.push(['aux:LensSerialNumber', aux.lensSerial]);
    A.push(['aux:ImageNumber', '0'],
           ['aux:ApproximateFocusDistance', aux.focusDistance || '4294967295/1'],
           ['aux:FlashCompensation', '0/1']);
    if (aux.firmware) A.push(['aux:Firmware', aux.firmware]);
    if (aux.corrected) A.push(['aux:DistortionCorrectionAlreadyApplied', 'True'],
                              ['aux:LateralChromaticAberrationCorrectionAlreadyApplied', 'True'],
                              ['aux:VignetteCorrectionAlreadyApplied', 'True']);
    if (lens?.model) A.push(['exifEX:LensModel', xml(lens.model)]);
  } else {
    A.push(['xmp:CreatorTool', editor.software], ['xmp:ModifyDate', modified],
           ['xmp:CreateDate', created], ['xmp:MetadataDate', modified]);
    if (lens?.lensInfo) A.push(['aux:LensInfo', lens.lensInfo]);
    if (lens?.auxLens)  A.push(['aux:Lens', xml(lens.auxLens)]);
    if (lens?.model)    A.push(['exifEX:LensModel', xml(lens.model)]);
  }
  A.push(['photoshop:DateCreated', created],
         ['xmpMM:DocumentID', `xmp.did:${id}`],
         ['xmpMM:OriginalDocumentID', original],
         ['xmpMM:InstanceID', `xmp.iid:${id}`],
         ['dc:format', 'image/jpeg'],
         ['crs:RawFileName', xml(source.fileName)]);
  const attrs = A.map(([k, v]) => `   ${k}="${v}"`).join('\n');
  const crs = crsAttributes({ editor, isRaw, scene, cameraProfile: source.cameraProfile || 'Adobe Color' });
  const derivedParams = isRaw
    ? `converted from ${source.mime} to image/jpeg, saved to new location`
    : 'saved to new location';
  const derivedFrom = isRaw
    ? `   <xmpMM:DerivedFrom\n    stRef:documentID="${original}"\n    stRef:originalDocumentID="${original}"/>`
    : `   <xmpMM:DerivedFrom\n    stRef:instanceID="xmp.iid:${uuid()}"\n    stRef:documentID="xmp.did:${uuid()}"\n    stRef:originalDocumentID="${original}"/>`;
  return `<?xpacket begin="\uFEFF" id="W5M0MpCehiHzreSzNTczkc9d"?>
<x:xmpmeta xmlns:x="adobe:ns:meta/" x:xmptk="${XMP_TOOLKIT}">
 <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
  <rdf:Description rdf:about=""
    xmlns:xmp="http://ns.adobe.com/xap/1.0/"
    xmlns:aux="http://ns.adobe.com/exif/1.0/aux/"
    xmlns:exifEX="http://cipa.jp/exif/1.0/"
    xmlns:photoshop="http://ns.adobe.com/photoshop/1.0/"
    xmlns:xmpMM="http://ns.adobe.com/xap/1.0/mm/"
    xmlns:stEvt="http://ns.adobe.com/xap/1.0/sType/ResourceEvent#"
    xmlns:stRef="http://ns.adobe.com/xap/1.0/sType/ResourceRef#"
    xmlns:dc="http://purl.org/dc/elements/1.1/"
    xmlns:crs="http://ns.adobe.com/camera-raw-settings/1.0/"
${attrs}
${crs}>
   <xmpMM:History>
    <rdf:Seq>
     <rdf:li
      stEvt:action="derived"
      stEvt:parameters="${derivedParams}"/>
     <rdf:li
      stEvt:action="saved"
      stEvt:instanceID="xmp.iid:${id}"
      stEvt:when="${modified}"
      stEvt:softwareAgent="${editor.software}"
      stEvt:changed="/"/>
    </rdf:Seq>
   </xmpMM:History>
${derivedFrom}
${TONE_CURVES}
${POINT_COLORS}
  </rdf:Description>
 </rdf:RDF>
</x:xmpmeta>${XMP_PADDING}<?xpacket end="w"?>`;
}

// ── Photoshop APP13 block ────────────────────────────────────────

const be32 = n => [(n >>> 24) & 0xFF, (n >>> 16) & 0xFF, (n >>> 8) & 0xFF, n & 0xFF];
const be16 = n => [(n >> 8) & 0xFF, n & 0xFF];

/** One "8BIM" image resource with an empty name, padded to an even length. */
function resource(id, data) {
  const out = [0x38, 0x42, 0x49, 0x4D, ...be16(id), 0x00, 0x00, ...be32(data.length), ...data];
  if (data.length % 2) out.push(0);
  return out;
}

/** One IPTC dataset: 0x1C, record, dataset, length, bytes. */
function dataset(rec, ds, bytes) {
  return [0x1C, rec, ds, ...be16(bytes.length), ...bytes];
}

/**
 * The APP13 Photoshop segment every Adobe export carries, measured from
 * seven of them: a resolution-info resource (the export ppi, inches), the
 * IPTC block (UTF-8 marker, record version 4, capture date and time with
 * zone, and the digital-creation pair), the thumbnail resource (a 28-byte
 * header then the very JPEG that sits in IFD1), and the MD5 of the IPTC
 * block as IPTCDigest. Order and encodings as in the files.
 */
export function buildPhotoshopApp13({ dpi, capture, offset, thumb, thumbWidth, thumbHeight }) {
  const pad = n => String(n).padStart(2, '0');
  const dateStr = `${capture.getFullYear()}${pad(capture.getMonth() + 1)}${pad(capture.getDate())}`;
  const timeStr = `${pad(capture.getHours())}${pad(capture.getMinutes())}${pad(capture.getSeconds())}${(offset || '+00:00').replace(':', '')}`;
  const ascii = s => Array.from(s, c => c.charCodeAt(0) & 0xFF);

  const res = [];
  res.push(...resource(0x03ED, [...be32(dpi << 16), 0, 1, 0, 1, ...be32(dpi << 16), 0, 1, 0, 1]));
  const iptc = [
    ...dataset(1, 90, [0x1B, 0x25, 0x47]),
    ...dataset(2, 0, [0x00, 0x04]),
    ...dataset(2, 55, ascii(dateStr)),
    ...dataset(2, 60, ascii(timeStr)),
    ...dataset(2, 62, ascii(dateStr)),
    ...dataset(2, 63, ascii(timeStr)),
  ];
  res.push(...resource(0x0404, iptc));
  if (thumb && thumb.length) {
    const widthBytes = Math.floor((thumbWidth * 24 + 31) / 32) * 4;
    const header = [...be32(1), ...be32(thumbWidth), ...be32(thumbHeight), ...be32(widthBytes),
                    ...be32(widthBytes * thumbHeight), ...be32(thumb.length), ...be16(24), ...be16(1)];
    res.push(...resource(0x040C, [...header, ...thumb]));
  }
  res.push(...resource(0x0425, Array.from(md5(Uint8Array.from(iptc)))));

  const body = [...ascii('Photoshop 3.0\0'), ...res];
  const len = body.length + 2;
  return Uint8Array.from([0xFF, 0xED, ...be16(len), ...body]);
}

/**
 * Wrap an XMP packet as an APP1 segment.
 *
 * The packet is UTF-8, and it matters: the xpacket header opens with U+FEFF,
 * which has to land as the three bytes EF BB BF. An earlier version masked
 * each code unit with 0xFF, so every file began its packet with a lone 0xFF
 * byte — invalid UTF-8 that readers tolerate silently, which made it a
 * deterministic signature of this writer.
 */
export function xmpSegment(packet) {
  const body = new TextEncoder().encode('http://ns.adobe.com/xap/1.0/\0' + packet);
  const len = body.length + 2;
  if (len > 0xFFFF) return null;
  const seg = new Uint8Array(2 + len);
  seg[0] = 0xFF; seg[1] = 0xE1;
  seg[2] = (len >> 8) & 0xFF; seg[3] = len & 0xFF;
  seg.set(body, 4);
  return seg;
}
