/** Adobe pads every packet with whitespace: 40 lines of 100 spaces and a short last line, 4097 bytes in all. */
const XMP_PADDING = '\n' + (' '.repeat(100) + '\n').repeat(40) + ' '.repeat(55) + '\n';

/**
 * Build the XMP packet an export carries, in the measured form.
 *
 * Two sources were measured: a Camera Raw export of a raw file, whose packet
 * leads with xmp:ModifyDate and carries the aux: block the raw supplied, and
 * a Lightroom export of a phone JPEG, which leads with xmp:CreatorTool. The
 * capture time goes to CreateDate and DateCreated; the export time to
 * ModifyDate, MetadataDate and the history entry. History entries are in
 * Adobe's compact attribute form, followed by DerivedFrom, the four tone
 * curves and PointColors, then the padding.
 */
export function buildXmpPacket({ capture, exportAt, offsetCapture, offsetExport, subsec,
                                 lens, editor, source, scene, aux = {}, crop = null }) {
  const id = uuidFor(editor.platform);
  const created  = xmpDate(capture, offsetCapture, subsec);
  const modified = xmpDate(exportAt, offsetExport);
  const original = hex(32).toUpperCase();
  const isRaw = !!source.raw;
  const A = [];
  if (isRaw) {
    A.push(['xmp:ModifyDate', modified], ['xmp:CreateDate', created],
           ['xmp:CreatorTool', editor.software], ['xmp:MetadataDate', modified]);
    if (aux.serialNumber) A.push(['aux:SerialNumber', aux.serialNumber]);
    if (lens?.lensInfo)   A.push(['aux:LensInfo', lens.lensInfo]);
    if (lens?.auxLens)    A.push(['aux:Lens', xml(lens.auxLens)]);
    if (aux.lensSerial)   A.push(['aux:LensSerialNumber', aux.lensSerial]);
    A.push(['aux:ImageNumber', '0'],
           ['aux:ApproximateFocusDistance', aux.focusDistance || '4294967295/1'],
           ['aux:FlashCompensation', '0/1']);
    if (aux.firmware) A.push(['aux:Firmware', aux.firmware]);
    if (aux.corrected) A.push(['aux:DistortionCorrectionAlreadyApplied', 'True'],
                              ['aux:LateralChromaticAberrationCorrectionAlreadyApplied', 'True'],
                              ['aux:VignetteCorrectionAlreadyApplied', 'True']);
    if (lens?.model) A.push(['exifEX:LensModel', xml(lens.model)]);
  } else {
    A.push(['xmp:CreatorTool', editor.software], ['xmp:ModifyDate', modified],
           ['xmp:CreateDate', created], ['xmp:MetadataDate', modified]);
    if (lens?.lensInfo) A.push(['aux:LensInfo', lens.lensInfo]);
    if (lens?.auxLens)  A.push(['aux:Lens', xml(lens.auxLens)]);
    if (lens?.model)    A.push(['exifEX:LensModel', xml(lens.model)]);
  }
  A.push(['photoshop:DateCreated', created],
         ['xmpMM:DocumentID', `xmp.did:${id}`],
         ['xmpMM:OriginalDocumentID', original],
         ['xmpMM:InstanceID', `xmp.iid:${id}`],
         ['dc:format', 'image/jpeg'],
         ['crs:RawFileName', xml(source.fileName)]);
  const attrs = A.map(([k, v]) => `   ${k}="${v}"`).join('\n');
  const crs = crsAttributes({ editor, isRaw, scene, profileDigest: source.profileDigest,
                             lensCorrection: source.lensCorrection, crop });
  const derivedParams = isRaw
    ? `converted from ${source.mime} to image/jpeg, saved to new location`
    : 'saved to new location';
  const derivedFrom = isRaw
    ? `   <xmpMM:DerivedFrom\n    stRef:documentID="${original}"\n    stRef:originalDocumentID="${original}"/>`
    : `   <xmpMM:DerivedFrom\n    stRef:instanceID="xmp.iid:${editor.platform === 'Macintosh' || rnd() < 0.4 ? uuidV4() : uuidPlain()}"\n    stRef:documentID="xmp.did:${uuidV4()}"\n    stRef:originalDocumentID="${original}"/>`;
  return `<?xpacket begin="\uFEFF" id="W5M0MpCehiHzreSzNTczkc9d"?>
<x:xmpmeta xmlns:x="adobe:ns:meta/" x:xmptk="${XMP_TOOLKIT}">
 <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
  <rdf:Description rdf:about=""
    xmlns:xmp="http://ns.adobe.com/xap/1.0/"
    xmlns:aux="http://ns.adobe.com/exif/1.0/aux/"
    xmlns:exifEX="http://cipa.jp/exif/1.0/"
    xmlns:photoshop="http://ns.adobe.com/photoshop/1.0/"
    xmlns:xmpMM="http://ns.adobe.com/xap/1.0/mm/"
    xmlns:stEvt="http://ns.adobe.com/xap/1.0/sType/ResourceEvent#"
    xmlns:stRef="http://ns.adobe.com/xap/1.0/sType/ResourceRef#"
    xmlns:dc="http://purl.org/dc/elements/1.1/"
    xmlns:crs="http://ns.adobe.com/camera-raw-settings/1.0/"
${attrs}
${crs}>
   <xmpMM:History>
    <rdf:Seq>
     <rdf:li
      stEvt:action="derived"
      stEvt:parameters="${derivedParams}"/>
     <rdf:li
      stEvt:action="saved"
      stEvt:instanceID="xmp.iid:${id}"
      stEvt:when="${modified}"
      stEvt:softwareAgent="${editor.software}"
      stEvt:changed="/"/>
    </rdf:Seq>
   </xmpMM:History>
${derivedFrom}
${TONE_CURVES}
${POINT_COLORS}${hasColorVariance(editor) ? `\n${COLOR_VARIANCE}` : ''}${isRaw ? `\n${lookBlock(editor)}` : ''}
  </rdf:Description>
 </rdf:RDF>
</x:xmpmeta>${XMP_PADDING}<?xpacket end="w"?>`;
}

