#!/usr/bin/env python3
"""Build js/exposure-tables.js, the real exposures generated photos draw from.

    python tools/exposure_tables.py <phone-survey.jsonl> <body-survey.jsonl> [out.js]

The inputs are Wikimedia Commons API surveys, one JSON object per file
(action=query, generator=categorymembers over "Taken with <model>" categories,
prop=imageinfo, iiprop=metadata|user), with at least: title, user, Make,
Software, ExposureTime, FNumber, ISOSpeedRatings, GPSLatitude, GPSLongitude
and their Ref fields, as Commons reports them.

Phones: (f-number, exposure time, ISO) of every phone file whose GPS lies in the United
States and that is not an Adobe export (an export's time is already rounded by
Adobe). US files only, because a phone locks its exposure time to the mains
flicker: US photos sit at 1/60 and 1/120 s and almost never at 1/50 or 1/100,
the other way round from photos taken where mains is 50 Hz. Two tables: Apple,
and Android (every non-Apple make).

Camera bodies: (f-number, exposure time, ISO, local hour of capture) of every
Adobe export of a body.

Rows are grouped by uploader, so the generator can weight every uploader
equally, as every other measured share in the project is weighted.
"""
import json, math, re, sys, collections

US_BOXES = [(24.5, 49.5, -125, -66.9), (18.5, 22.5, -161, -154), (51, 71.5, -170, -130)]


def frac(v):
    try:
        v = str(v)
        if '/' in v:
            n, d = (float(x) for x in v.split('/'))
            return n / d if d else None
        return float(v)
    except ValueError:
        return None


def iso_of(v):
    try:
        return float(str(v).split()[0].strip('[],'))
    except ValueError:
        return None


def rows(path):
    seen = set()
    for line in open(path, encoding='utf-8'):
        r = json.loads(line)
        if r['title'] in seen: continue
        seen.add(r['title'])
        t, f, iso = frac(r.get('ExposureTime')), frac(r.get('FNumber')), iso_of(r.get('ISOSpeedRatings'))
        if not (t and f and iso and t > 0 and f > 0 and iso > 0): continue
        ev = math.log2(f * f / t) - math.log2(iso / 100)
        if not -6 <= ev <= 20: continue
        r.update(t=t, f=f, iso=iso)
        yield r


def adobe(r):
    s = str(r.get('Software'))
    return 'Lightroom' in s or 'Camera Raw' in s


def in_us(r):
    try:
        la, lo = float(r['GPSLatitude']), float(r['GPSLongitude'])
    except (TypeError, ValueError, KeyError):
        return False
    if r.get('GPSLatitudeRef') == 'S': la = -abs(la)
    if r.get('GPSLongitudeRef') == 'W': lo = -abs(lo)
    return any(a <= la <= b and c <= lo <= d for a, b, c, d in US_BOXES)


def num(x, digits):
    s = f'{float(f"{x:.{digits}g}"):.{digits}g}'
    return s[:-2] if s.endswith('.0') else s


def encode(groups, fields):
    """Uploaders separated by '|', a file's values by ',', files by ' '."""
    out = []
    for user in sorted(groups):
        out.append(' '.join(','.join(fn(r) for fn in fields) for r in sorted(groups[user], key=lambda r: r['title'])))
    return '|'.join(out)


def main(phone_path, body_path, out_path):
    make_family = lambda r: 'apple' if str(r.get('Make') or '').strip().lower() in ('apple', 'iphone') else 'android'
    phones = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in rows(phone_path):
        if not r.get('Make') or adobe(r) or not in_us(r): continue
        phones[make_family(r)][r['user']].append(r)
    bodies = collections.defaultdict(list)
    for r in rows(body_path):
        if adobe(r) and re.match(r'\d{4}:\d\d:\d\d \d\d', str(r.get('DateTimeOriginal'))): bodies[r['user']].append(r)

    inv = lambda r: num(1 / r['t'], 4)
    iso = lambda r: num(r['iso'], 6)
    fno = lambda r: num(r['f'], 3)
    hour = lambda r: str(int(str(r.get('DateTimeOriginal'))[11:13]))
    count = lambda g: (sum(len(v) for v in g.values()), len(g))
    a, an, b = count(phones['apple']), count(phones['android']), count(bodies)
    js = f"""/**
 * exposure-tables.js — real exposures, the ones generated photos draw from.
 *
 * Generated by tools/exposure_tables.py from Wikimedia Commons API surveys
 * read on 2026-10-18 (prop=imageinfo, iiprop=metadata); do not edit by hand.
 *
 * Each table is a string: uploaders separated by '|', files by ' ', a file's
 * values by ','. Exposure times are written as 1/t, to four significant digits.
 *
 * PHONE_APPLE, PHONE_ANDROID: "f-number,1/t,ISO" of phone photos located in the United
 * States that are not Adobe exports. Apple: {a[0]} files from {a[1]} uploaders
 * ("Taken with" iPhone XR to iPhone 16 Pro). Android: {an[0]} files from {an[1]}
 * uploaders (Pixel 6a to 8 Pro, Galaxy S21 to S24 Ultra and A54, OnePlus 12;
 * almost all of the US files are Pixels).
 *
 * BODY_ADOBE: "f-number,1/t,ISO,hour" of {b[0]} Adobe exports of camera-body
 * photos from {b[1]} uploaders (14 "Taken with" body categories: Canon, Nikon,
 * Sony, Fujifilm), the hour being DateTimeOriginal's, the camera's clock.
 */

export const PHONE_APPLE = '{encode(phones['apple'], (fno, inv, iso))}';

export const PHONE_ANDROID = '{encode(phones['android'], (fno, inv, iso))}';

export const BODY_ADOBE = '{encode(bodies, (fno, inv, iso, hour))}';
"""
    open(out_path, 'w', encoding='utf-8', newline='\n').write(js)
    print(f'apple {a}, android {an}, bodies {b}; {len(js)} bytes -> {out_path}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'js/exposure-tables.js')
